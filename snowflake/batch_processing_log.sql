CREATE TABLE IF NOT EXISTS ECOMMERCE.RAW.BATCH_INGESTION_LOG (
    BATCH_FOLDER VARCHAR NOT NULL,
    PROCESSED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    DBT_COMPLETED_AT TIMESTAMP_NTZ;
);


--Manual MERGE and UPDATE for first batch
MERGE INTO ECOMMERCE.RAW.BATCH_INGESTION_LOG AS target
USING (
    SELECT 'batch_2016-09' AS BATCH_FOLDER
) AS source
    ON target.BATCH_FOLDER = source.BATCH_FOLDER
WHEN NOT MATCHED THEN
    INSERT (BATCH_FOLDER)
    VALUES (source.BATCH_FOLDER);


UPDATE ECOMMERCE.RAW.BATCH_INGESTION_LOG
SET DBT_COMPLETED_AT = CURRENT_TIMESTAMP()
WHERE BATCH_FOLDER = 'batch_2016-09'
  AND DBT_COMPLETED_AT IS NULL;