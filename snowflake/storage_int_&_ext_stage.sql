CREATE OR REPLACE STORAGE INTEGRATION ECOMMERCE_S3_INT
TYPE = EXTERNAL_STAGE
STORAGE_PROVIDER = 'S3'
ENABLED = TRUE
STORAGE_AWS_ROLE_ARN = 'IAM_ROLE_ARN' 
STORAGE_ALLOWED_LOCATIONS = ('BUCKET_LOCATION/');



CREATE FILE FORMAT IF NOT EXISTS
    ECOMMERCE_DB.RAW.ECOMMERCE_CSV_FORMAT
    TYPE = CSV
    FIELD_DELIMITER = ','
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    SKIP_HEADER = 1
    EMPTY_FIELD_AS_NULL = TRUE;

CREATE STAGE IF NOT EXISTS
    ECOMMERCE_DB.RAW.ECOMMERCE_STAGE
    URL = 'BUCKET_LOCATION/'
    STORAGE_INTEGRATION = ECOMMERCE_S3_INT
    FILE_FORMAT = 'ECOMMERCE_DB.RAW.ECOMMERCE_CSV_FORMAT';