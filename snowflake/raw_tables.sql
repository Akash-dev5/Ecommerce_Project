-- Reference tables

CREATE TABLE IF NOT EXISTS ECOMMERCE_DB.RAW.RAW_PRODUCTS (
    PRODUCT_ID VARCHAR,
    PRODUCT_CATEGORY_NAME VARCHAR,
    PRODUCT_NAME_LENGHT NUMBER,
    PRODUCT_DESCRIPTION_LENGHT NUMBER,
    PRODUCT_PHOTOS_QTY NUMBER,
    PRODUCT_WEIGHT_G NUMBER,
    PRODUCT_LENGTH_CM NUMBER,
    PRODUCT_HEIGHT_CM NUMBER,
    PRODUCT_WIDTH_CM NUMBER
);

CREATE TABLE IF NOT EXISTS ECOMMERCE_DB.RAW.RAW_SELLERS (
    SELLER_ID VARCHAR,
    SELLER_ZIP_CODE_PREFIX VARCHAR,
    SELLER_CITY VARCHAR,
    SELLER_STATE VARCHAR
);

CREATE TABLE IF NOT EXISTS ECOMMERCE_DB.RAW.RAW_GEOLOCATION (
    GEOLOCATION_ZIP_CODE_PREFIX VARCHAR,
    GEOLOCATION_LAT NUMBER(12,8),
    GEOLOCATION_LNG NUMBER(12,8),
    GEOLOCATION_CITY VARCHAR,
    GEOLOCATION_STATE VARCHAR
);

CREATE TABLE IF NOT EXISTS
    ECOMMERCE_DB.RAW.RAW_PRODUCT_CATEGORY_TRANSLATION (
    PRODUCT_CATEGORY_NAME VARCHAR,
    PRODUCT_CATEGORY_NAME_ENGLISH VARCHAR
);



-- Monthly transactional tables

CREATE TABLE IF NOT EXISTS ECOMMERCE_DB.RAW.RAW_ORDERS (
    ORDER_ID VARCHAR,
    CUSTOMER_ID VARCHAR,
    ORDER_STATUS VARCHAR,
    ORDER_PURCHASE_TIMESTAMP TIMESTAMP_NTZ,
    ORDER_APPROVED_AT TIMESTAMP_NTZ,
    ORDER_DELIVERED_CARRIER_DATE TIMESTAMP_NTZ,
    ORDER_DELIVERED_CUSTOMER_DATE TIMESTAMP_NTZ,
    ORDER_ESTIMATED_DELIVERY_DATE TIMESTAMP_NTZ
);

CREATE TABLE IF NOT EXISTS ECOMMERCE_DB.RAW.RAW_CUSTOMERS (
    CUSTOMER_ID VARCHAR,
    CUSTOMER_UNIQUE_ID VARCHAR,
    CUSTOMER_ZIP_CODE_PREFIX VARCHAR,
    CUSTOMER_CITY VARCHAR,
    CUSTOMER_STATE VARCHAR
);

CREATE TABLE IF NOT EXISTS ECOMMERCE_DB.RAW.RAW_ORDER_ITEMS (
    ORDER_ID VARCHAR,
    ORDER_ITEM_ID NUMBER,
    PRODUCT_ID VARCHAR,
    SELLER_ID VARCHAR,
    SHIPPING_LIMIT_DATE TIMESTAMP_NTZ,
    PRICE NUMBER(12,2),
    FREIGHT_VALUE NUMBER(12,2)
);

CREATE TABLE IF NOT EXISTS ECOMMERCE_DB.RAW.RAW_PAYMENTS (
    ORDER_ID VARCHAR,
    PAYMENT_SEQUENTIAL NUMBER,
    PAYMENT_TYPE VARCHAR,
    PAYMENT_INSTALLMENTS NUMBER,
    PAYMENT_VALUE NUMBER(12,2)
);

CREATE TABLE IF NOT EXISTS ECOMMERCE_DB.RAW.RAW_REVIEWS (
    REVIEW_ID VARCHAR,
    ORDER_ID VARCHAR,
    REVIEW_SCORE NUMBER,
    REVIEW_COMMENT_TITLE VARCHAR,
    REVIEW_COMMENT_MESSAGE VARCHAR,
    REVIEW_CREATION_DATE TIMESTAMP_NTZ,
    REVIEW_ANSWER_TIMESTAMP TIMESTAMP_NTZ
);